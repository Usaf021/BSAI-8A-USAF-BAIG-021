"""
Week 4 · Part C — part-to-whole legality, and the pie-ranking experiment.

    python3 partC_shares.py              # C.1 legality tests + builds the two stimuli PNGs
    python3 partC_shares.py --run NAME   # C.2: run the timed experiment on ONE real reader

The experiment results are NEVER generated by this script. pie_ranking_results.csv is
written only by --run, from what a person actually typed and how long it took.
"""
import os
import sys
import time
import matplotlib
import numpy as np
import pandas as pd

import tslib
from vizlib import PALETTE, style_defaults, save_fig

HERE = os.path.dirname(os.path.abspath(__file__))
D = os.path.join(HERE, "data")
sh = pd.read_csv(f"{D}/shares_eight.csv")
TRUE_ORDER = list(sh.sort_values("share_pct", ascending=False).slice)
RESULTS = os.path.join(HERE, "pie_ranking_results.csv")


def stimuli():
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    style_defaults()
    fig, ax = plt.subplots(figsize=(6, 6))
    cols = ["#0072B2", "#D55E00", "#009E73", "#CC79A7", "#E69F00", "#56B4E9", "#F0E442", "#7F7F7F"]
    ax.pie(sh.share_pct, labels=sh.slice, colors=cols, startangle=90, counterclock=False,
           textprops={"fontsize": 14}, wedgeprops={"edgecolor": "white"})
    ax.set_title("Rank slices A–H, largest first")
    save_fig(fig, os.path.join(HERE, "partC_stimulus_pie.png")); plt.close(fig)
    fig, ax = plt.subplots(figsize=(6, 4.5))
    b = sh.sort_values("share_pct")
    ax.barh(b.slice, b.share_pct, color=PALETTE["series"][0]); ax.set_xlabel("Share, % of the eight-category total")
    ax.set_title("Rank slices A–H, largest first")
    save_fig(fig, os.path.join(HERE, "partC_stimulus_bars.png")); plt.close(fig)


def wrong_letters(order):
    pos = {c: i for i, c in enumerate(TRUE_ORDER)}
    return [c for i, c in enumerate(order) if pos[c] != i], [i + 1 for i, c in enumerate(order) if pos[c] != i]


def run(reader):
    import subprocess
    rows = []
    for name, f in [("pie", "partC_stimulus_pie.png"), ("bars", "partC_stimulus_bars.png")]:
        subprocess.Popen(["open", os.path.join(HERE, f)])
        input(f"\n[{name}] Press Enter when the reader is ready to see it (image opens). Timer starts at Enter...")
        t0 = time.perf_counter()
        ans = input("Reader's order, largest first (e.g. ABCDEFGH): ").strip().upper().replace(" ", "").replace(",", "")
        sec = time.perf_counter() - t0
        rows.append({"reader": reader, "stimulus": name, "order": ans, "seconds": round(sec, 1)})
    df = pd.DataFrame(rows)
    df.to_csv(RESULTS, mode="a", header=not os.path.exists(RESULTS), index=False)
    print(df)


def score():
    r = pd.read_csv(RESULTS)
    for _, x in r.iterrows():
        w, p = wrong_letters(list(x.order))
        print(f"{x.reader:<10} {x.stimulus:<5} {x.seconds:>6.1f}s  misplaced {len(w)}: {w} at ranks {p}")


if __name__ == "__main__":
    if "--run" in sys.argv:
        run(sys.argv[sys.argv.index("--run") + 1]); score(); sys.exit()
    if "--score" in sys.argv:
        score(); sys.exit()

    print("== C.1  the three conditions, tested ==")
