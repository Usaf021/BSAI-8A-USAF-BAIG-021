    print("   VERDICT: neither pie nor stacked/treemap. A bar chart of reach per channel, each against all 4,000 customers.")

    print("\n(b) shares_eight.csv:")
    tot = sh.share_pct.sum(); print(f"   sum = {tot:.4f}  assert |sum-100|<1e-6 ->", abs(tot - 100) < 1e-6)
    cat = pd.read_csv(f"{D}/revenue_catalogue.csv").drop_duplicates("sku")
    print(f"   exclusive: each SKU in one sub-category after dedupe (nunique parents per sub = "
          f"{cat.groupby('subcategory').category.nunique().max()}) | whole = net revenue of the catalogue | share IS the question (where does the money sit?)")
    print("   VERDICT: legal as a pie, but eight slices with three within 4 points of each other (C 15.0, H 13.1, G 11.2) "
          "is beyond what angle can rank -> sorted horizontal bar chart (position on a common scale). Pie only if the "
          "question were 'is Phones about a quarter?'.")

    z = pd.read_csv(f"{D}/case09_premium_share.csv").iloc[-1]
    prem, tot9 = z.premium_revenue_pkr_m, z.total_revenue_pkr_m
    print(f"\n(c) 2025Q4 premium {prem} vs other {tot9 - prem:.1f}, whole {tot9}: share {prem / tot9:.1%}")
    print("   exclusive: yes (premium and not-premium) | whole meaningful: yes, all Q4 revenue | share is the question: "
          "for a single quarter yes.")
    print("   VERDICT: a pie or a single 100% bar of the two parts is legal for the 2025Q4 snapshot (two slices, one "
          "comparison to 50%); NOT for the trend — a share line hides that premium is flat and the total fell 40% (Part A case 9).")
    stimuli()
    print("\nwrote partC_stimulus_pie.png and partC_stimulus_bars.png")
    print("TRUE ORDER:", " > ".join(f"{s}({v})" for s, v in sh.sort_values('share_pct', ascending=False)[['slice', 'share_pct']].values))
    print("Run the experiment on a real person: python3 partC_shares.py --run <reader-name>")
    print("State your rule (C.4): I will draw a pie only for two (at most three) parts of a meaningful whole where "
          "the question is 'about half / about a quarter?', never for more than five parts and never for a trend.")
